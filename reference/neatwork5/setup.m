
function setup()
%SETUP  Ajoute les sous-dossiers MATLAB du projet NW_Git au path.
%
% Appeler cette fonction une fois après avoir ouvert MATLAB :
%   setup

root = fileparts(mfilename('fullpath'));

folders = { ...
    fullfile(root, 'matlab'), ...
    fullfile(root, 'out'), ...
    fullfile(root, 'utils'), ...
    fullfile(root, 'examples'), ...
    fullfile(root, 'examples','tpo_examples'), ...
    fullfile(root, 'examples','dsg_examples'), ...
    fullfile(root, 'matlab', 'Simul'), ...
    fullfile(root, 'matlab', 'InOut'), ...
    fullfile(root, 'matlab', 'CreateDsgDev'),...
    fullfile(root, 'tests', 'matlab'), ...
    % Ajouter ici d'autres dossiers si besoin
};
for k = 1:numel(folders)
    if isfolder(folders{k})
        addpath(folders{k});
    end
end

% Exclusion des dossiers contenant "reserve"
p = path;  % chaîne de caractères du path courant
p = regexprep(p, ['[^', pathsep, ']*reserve[^', pathsep, ']*', pathsep], '');
path(p);

fprintf('[NW_Git] MATLAB paths added (excluding "reserve").\nRoot: %s\n', root);
end
