function result = reducePipeMixture(x, resistance, cost)
%REDUCEPIPEMIXTURE Lower cost envelope of the pipes used on one link.
% resistance contains the equivalent linear coefficients from TR for this
% link, including the existing pipe (which may be fictive). Preserve both
% sum(x) and resistance'*x; use at most two of the initially active pipes.
    x = x(:); resistance = resistance(:); cost = cost(:);
    assert(numel(x)==numel(resistance) && numel(x)==numel(cost) && ...
        all(isfinite(x) & x>=0) && ...
        all(isfinite(resistance) & resistance>0) && ...
        all(isfinite(cost) & cost>=0), ...
        'NW5:Mixture','Invalid pipe mixture data.');
    active = find(x>0);
    result = x;
    if numel(active)<=2, return; end

    mass = sum(x);
    target = (resistance'*x)/mass;
    % Increasing resistance; retain the cheapest pipe at equal resistance.
    [~,order] = sortrows([resistance(active),cost(active)],[1 2]);
    ids = active(order);
    ids = ids([true;diff(resistance(ids))>0]);

    % Lower convex hull: consecutive slopes must be strictly increasing.
    hull = zeros(numel(ids),1);
    count = 0;
    for k = 1:numel(ids)
        c = ids(k);
        while count>=2
            a = hull(count-1); b = hull(count);
            left = (cost(b)-cost(a))*(resistance(c)-resistance(b));
            right = (cost(c)-cost(b))*(resistance(b)-resistance(a));
            if left<right, break; end
            count = count-1;
        end
        count = count+1;
        hull(count) = c;
    end
    hull = hull(1:count);
    result = zeros(size(x));
    if count==1 || target<=resistance(hull(1))
        result(hull(1)) = mass;
    elseif target>=resistance(hull(end))
        result(hull(end)) = mass;
    else
        k = find(resistance(hull)>=target,1);
        a = hull(k-1); b = hull(k);
        weight = (resistance(b)-target)/(resistance(b)-resistance(a));
        result(a) = mass*weight;
        result(b) = mass*(1-weight);
    end

    % The following assertions are not strictly necessary, but they are useful to detect 
    % numerical issues in the convex hull algorithm. They are not guaranteed to hold
    % for arbitrary inputs, but they should hold for the specific inputs generated by
    % the NW5 design algorithm. Very defensive.
    
    % Equality constraint: neither lower nor higher resistance is allowed,
    % apart from floating-point roundoff. Only cost may improve.
    assert(abs(resistance'*result-resistance'*x) <= ...
        1e-10*max(abs(resistance'*x),realmin('double')), ...
        'NW5:Mixture','Pipe reduction changed the target resistance.');
    assert(cost'*result <= cost'*x+1e-10*max(1,abs(cost'*x)), ...
        'NW5:Mixture','Pipe reduction increased the cost.');
end
