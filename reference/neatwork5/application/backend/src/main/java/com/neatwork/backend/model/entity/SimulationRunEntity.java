package com.neatwork.backend.model.entity;

import com.neatwork.backend.enums.SimulationConfigurationMode;
import com.neatwork.backend.enums.SimulationJobStatus;
import jakarta.persistence.*;

import lombok.*;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;


@Entity
@Table(name = "simulation_runs")
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class SimulationRunEntity {

    // Persistent identifier of one completed simulation run.
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    // Project owning this simulation result.
    @Column(nullable = false)
    private UUID projectId;

    /**
     * Stable human-readable simulation number within one project.
     * Numbers are never reused after a simulation has been deleted.
     */
    @Column(name = "run_number", nullable = false)
    private int runNumber;

    /**
     * Immutable domain snapshot selected when the simulation is submitted.
     * It must never be replaced with a newer snapshot while the simulation is running.
     */
    @Column(nullable = false)
    private UUID domainSnapshotId;

    // Persistent asynchronous lifecycle state.
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 64)
    private SimulationJobStatus status;

    // Describes whether this execution was started with project defaults or manual runtime settings.
    @Enumerated(EnumType.STRING)
    @Column(name = "configuration_mode", nullable = false, length = 16)
    private SimulationConfigurationMode configurationMode;

    // Exact runtime overrides requested by the user. An empty object means DEFAULT execution.
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "requested_options_json", columnDefinition = "jsonb", nullable = false)
    private Map<String, Object> requestedOptionsJson;


    // Fully resolved values actually used by the Python numerical engine.
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "resolved_options_json", columnDefinition = "jsonb")
    private Map<String, Object> resolvedOptionsJson;

    /**
     * Describes where every resolved parameter came from.
     * Examples:
     * USER_OVERRIDE
     * PROJECT_DEFAULT
     * GENERATED
     * NOT_APPLICABLE
     */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "parameter_sources_json", columnDefinition = "jsonb")
    private Map<String, Object> parameterSourcesJson;

    // OPEN/CLOSED edge states captured when the simulation was submitted.
     // These values are immutable execution input.
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "edge_overrides_json", columnDefinition = "jsonb", nullable = false)
    private List<Map<String, Object>> edgeOverridesJson;

    // Exact source artifact used by this simulation.
    private UUID inputArtifactId;

    // Human-readable network name such as Toy or Esperanza.
    private String inputName;

    // Exact DSG/TPO filename used by this execution.
    private String inputFilename;

    // Immutable revision number of the source artifact.
    private Integer inputVersion;

    // DSG or TPO.
    private String inputSourceFormat;

    /**
     * Complete simulation response persisted after successful Python execution.
     * Keeping the response here makes job polling independent from in-memory Java state.
     */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(columnDefinition = "jsonb")
    private Map<String, Object> resultJson;

    // Canonical statistics generated by Python. Canonical strict-JSON statistics.
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(columnDefinition = "jsonb")
    private Map<String, Object> statisticsJson;

    // Python-level result status.
    // This is intentionally different from the asynchronous execution lifecycle status.
    @Column(name = "result_status", length = 64)
    private String resultStatus;

    // Reproducibility seed returned by Python. Null while the simulation has not completed.
    private Long seed;

    // Number of scenarios used by the execution. Null while no result exists.
    private Integer scenarioCount;
    @Builder.Default
    @Column(nullable = false)
    private boolean cancelRequested = false;

    @Column(columnDefinition = "text")
    private String errorMessage;

    @Column(nullable = false)
    private Instant createdAt;

    private Instant startedAt;

    private Instant completedAt;

    @Column(nullable = false)
    private Instant updatedAt;

    @PrePersist
    void prePersist() {
        var now = Instant.now();
        if (createdAt == null) {
            createdAt = now;
        }
        if (updatedAt == null) {
            updatedAt = now;
        }
        if (status == null) {
            status =
                    SimulationJobStatus.PENDING;
        }
    }

    @PreUpdate
    void preUpdate() {
        updatedAt = Instant.now();
    }
}
